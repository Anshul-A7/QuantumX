def make_cell(cell_type, source_lines):
    cell = {
        "cell_type": cell_type,
        "id": uuid.uuid4().hex[:8],
        "metadata": {},
        "source": [line + "\n" for line in source_lines]
    }
    if cell_type == "code":
        cell["execution_count"] = None
        cell["outputs"] = []
    return cell

def code_cell(lines):
    return make_cell("code", lines)

def md_cell(lines):
    return make_cell("markdown", lines)

