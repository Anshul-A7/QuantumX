        "            nn.Linear(in_features, 64),",
        "            nn.BatchNorm1d(64),",
        "            nn.Mish(),",
        "            nn.Dropout(0.15)",
        "        )",
        "        self.fusion = BilinearGatedFusion(q_dim=16, c_dim=64, out_dim=64)",
        "        self.classifier = nn.Sequential(",
        "            nn.Linear(64, 32),",
        "            nn.Mish(),",
        "            nn.Linear(32, num_classes)",
